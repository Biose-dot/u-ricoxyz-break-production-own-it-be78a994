import os

ENTRY = "ERROR 500: I deleted prod to test the backup. The backup was a screenshot of prod. The rollback plan is this error message. I have updated my resume."

def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "entry.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(ENTRY)

if __name__ == "__main__":
    main()
